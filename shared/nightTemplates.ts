/**
 * 夜景提示词**模板库**（P1-1）。
 *
 * 设计意图：把 `server/utils/agent/knowledge.ts` 里沉淀的领域知识，
 * 从「只有 Agent 内部能看到」变成「用户可复用的一等公民」。
 *
 * 放在 `shared/` 下，前后端共用：
 * - 前端：在生成面板展示模板卡片，一键填充提示词；
 * - 后端：Agent 可通过 `list_night_templates` / `get_night_template` 工具检索与引用，
 *   避免每次从零自由发挥导致质量方差大。
 *
 * 每个模板都按 `knowledge.ts` 的结构规范组织：
 * 背景 → 主体元素 → 灯光 → 地面 → 广告牌 → 氛围 → 风格 → 禁止项
 */

export type NightTemplate = {
  id: string
  name: string
  /** 一句话描述，用于卡片副标题 */
  summary: string
  /** 适用场景标签 */
  tags: string[]
  /** 完整正向提示词（可直接投喂出图） */
  prompt: string
  /** 建议的负向提示词 */
  negativePrompt: string
  /** 这条模板的「设计要点」，帮用户理解为什么这么写 */
  highlights: string[]
}

/** 所有模板共用的负向基础规则 */
const BASE_NEGATIVE = [
  '白天场景',
  '室内灯光明显高于室外灯光',
  '模糊不清的广告牌文字',
  '乱码文字',
  '低清晰度',
  '噪点',
  '涂抹感',
  '重影',
  '畸变',
  '过曝',
  '死黑阴影',
  '不真实灯光',
]

function joinNegative(extra: string[] = []) {
  return [...BASE_NEGATIVE, ...extra].join('；')
}

