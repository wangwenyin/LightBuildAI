/** 按 id 取模板 */
export function getNightTemplateById(id: string) {
  return NIGHT_TEMPLATES.find(item => item.id === id) || null
}

/**
 * 按关键词检索模板（匹配 name / summary / tags）。
 * 空关键词返回全部，供 Agent「先看看有哪些模板可用」。
 */
export function searchNightTemplates(keyword?: string) {
  const query = (keyword || '').trim().toLowerCase()

  if (!query) {
    return NIGHT_TEMPLATES
  }

  return NIGHT_TEMPLATES.filter((item) => {
    const haystack = [item.name, item.summary, ...item.tags].join(' ').toLowerCase()
    return haystack.includes(query)
  })
}
